"""Fast Action Refinement approach (Algorithm 1) from Section IV-B of Zhang et al. (IEEE JSAC 2023).

Ensures the continuous proto-action generated by the actor network is mapped to a valid,
feasible discrete offloading and resource allocation decision satisfying constraints C1-C4, (5), and (10).
"""

from typing import List, Tuple
import numpy as np
from .task_generator import Task


class FastActionRefiner:
    """Algorithm 1: Fast Action Refinement approach."""

    def __init__(self, num_bs: int = 3):
        self.num_bs = num_bs

    def refine_action(
        self,
        continuous_action: np.ndarray,
        tasks: List[Task],
        bs_computing_capacities: List[float],
        energy_buffers: np.ndarray,
        wireless_rates: np.ndarray,
        inter_bs_rate: float,
    ) -> Tuple[np.ndarray, np.ndarray, np.ndarray, dict]:
        """Executes Algorithm 1 to refine actor output into a feasible decision tuple.

        Args:
            continuous_action: Array of shape (M, num_bs + 1), where M is total tasks (165).
                               First entry a_hat_0 represents discard preference,
                               entries 1..num_bs represent offloading to BS i' (0..num_bs-1).
            tasks: List of Task objects at time slot t.
            bs_computing_capacities: Available CPU capacity Fi(t) for each BS (e.g. [5e9, 5e9, 5e9]).
            energy_buffers: Array of stored battery energy Q_ij^E(t) for each device.
            wireless_rates: Array of wireless transmission rates iota_ij(t) for each device.
            inter_bs_rate: Wired backhaul data transmission rate C_i'_i between BSs (100 Mbps).

        Returns:
            x: Binary offloading decisions of shape (M,)
            y: Binary peer offloading decisions of shape (M, num_bs)
            f: Allocated CPU frequencies of shape (M, num_bs)
            stats: Dictionary tracking refinement statistics
        """
        num_tasks = len(tasks)
        stats = {
            "initial_infeasible_actions": 0,
            "energy_constraint_violations": 0,
            "capacity_constraint_violations": 0,
            "refined_discards": 0,
        }

        # Step 1: Nearest neighbor discrete action a'(t) according to Eq. (15)
        # For each task, select discrete target k in {0 (discard), 1..N (offload to BS 1..N)}
        target_indices = np.argmax(continuous_action, axis=1)

        x_prime = np.zeros(num_tasks, dtype=int)
        y_prime = np.zeros((num_tasks, self.num_bs), dtype=int)

        for m in range(num_tasks):
            target = target_indices[m]
            if target == 0:
                # Discard
                x_prime[m] = 0
            else:
                # Offload to BS (target - 1)
                x_prime[m] = 1
                y_prime[m, target - 1] = 1

        # Step 2: Modify action a'(t) according to energy constraint (5), (16), and (17)
        x_hat = x_prime.copy()
        y_hat = y_prime.copy()

        for m, task in enumerate(tasks):
            if x_hat[m] == 1:
                # Wireless delay d_ij^w(t) = z_ij(t) / iota_ij(t) (Eq. 4)
                rate = wireless_rates[m]
                if rate <= 0:
                    d_w = float("inf")
                else:
                    d_w = task.z / rate

                # Energy consumption p_ij * d_ij^w(t) <= Q_ij^E(t) (Eq. 5)
                energy_needed = task.p * d_w
                if energy_needed > energy_buffers[m] or d_w > task.delta:
                    # Energy constraint violated or wireless delay alone exceeds deadline
                    x_hat[m] = 0
                    y_hat[m, :] = 0
                    stats["energy_constraint_violations"] += 1

        # Step 3-8: Refine action to meet computing resource constraint (10)
        # Allocate minimum required computing resource l_i'_ij(t) according to Eq. (18)
        # and calculate priority rho_ij(t) = g_ij(t) / l_i'_ij(t)
        f_allocated = np.zeros((num_tasks, self.num_bs), dtype=float)

        for target_bs in range(self.num_bs):
            # Line 4: Obtain set of tasks Upsilon_i to be processed in BS i'
            assigned_task_indices = [
                m for m in range(num_tasks)
                if x_hat[m] == 1 and y_hat[m, target_bs] == 1
            ]

            # Calculate l_i'_ij(t) and priority rho_ij(t) for each candidate task
            task_priorities = []
            min_resources = {}

            for m in assigned_task_indices:
                task = tasks[m]
                # Wireless delay
                d_w = task.z / wireless_rates[m]

                # Inter-BS delay d_ij^c(t) = z_ij(t) / C_i'_i if target_bs != serving_bs else 0
                if target_bs == task.bs_id:
                    d_c = 0.0
                else:
                    d_c = task.z / inter_bs_rate

                remaining_time = task.delta - d_w - d_c
                if remaining_time <= 1e-6:
                    # Cannot be completed within deadline even with infinite CPU
                    l_req = float("inf")
                    priority = -1.0
                else:
                    # Eq. (18): l_i'_ij(t) = z_ij(t) * v_ij(t) / (delta_ij(t) - d_ij^w(t) - d_ij^c(t))
                    l_req = (task.z * task.v) / remaining_time
                    # Processing priority: rho_ij(t) = g_ij(t) / l_i'_ij(t)
                    priority = task.g / l_req

                min_resources[m] = l_req
                task_priorities.append((priority, m))

            # Line 5-8: while constraint (10) is not satisfied
            # Sort by priority ascending (lowest priority first to discard)
            task_priorities.sort(key=lambda item: item[0])

            capacity = bs_computing_capacities[target_bs]
            active_tasks = [m for priority, m in task_priorities if priority > 0 and min_resources[m] <= capacity]

            # Filter out tasks that exceed capacity by themselves
            for priority, m in task_priorities:
                if priority <= 0 or min_resources[m] > capacity:
                    x_hat[m] = 0
                    y_hat[m, :] = 0
                    stats["capacity_constraint_violations"] += 1

            # While sum of required resources exceeds capacity Fi'(t)
            while sum(min_resources[m] for m in active_tasks) > capacity:
                # Discard task with lowest priority rho_ij(t)
                dropped_idx = active_tasks.pop(0)
                x_hat[dropped_idx] = 0
                y_hat[dropped_idx, :] = 0
                stats["capacity_constraint_violations"] += 1
                stats["refined_discards"] += 1

            # For remaining admitted tasks in BS target_bs, allocate computing resource
            if active_tasks:
                total_min_req = sum(min_resources[m] for m in active_tasks)
                spare_capacity = max(0.0, capacity - total_min_req)
                for m in active_tasks:
                    # Give each task its required CPU plus proportional share of spare capacity
                    share = (min_resources[m] / total_min_req) * spare_capacity if total_min_req > 0 else 0.0
                    f_allocated[m, target_bs] = min_resources[m] + share

        return x_hat, y_hat, f_allocated, stats
